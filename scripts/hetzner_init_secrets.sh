#!/usr/bin/env bash
# One-time secret bootstrap for the Hetzner server. Run ON THE SERVER from the
# repo root (see directives/hetzner-deployment.md).
#
#   scripts/hetzner_init_secrets.sh <incoming.env> <site-host>
#
# incoming.env : a copy of the local root .env, scp'd to the server beforehand.
# site-host    : public hostname, e.g. 2-29-47-89.nip.io
#
# What it does:
#   * generates POSTGRES_PASSWORD, SESSION_SECRET and a new admin password
#   * writes ./.env (pipeline + API secrets) and services/dashboard/.env.compose
#   * stores the plaintext admin password in /root/inboxgenius_admin_password.txt
#     (chmod 600, outside the repo) -- read it yourself with `cat` in your own
#     terminal; this script NEVER prints any secret value.
# It refuses to overwrite an existing .env / .env.compose.
set -euo pipefail
umask 077

INCOMING="${1:?usage: $0 <incoming.env> <site-host>}"
SITE_HOST="${2:?usage: $0 <incoming.env> <site-host>}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DASH_DIR="$REPO_ROOT/services/dashboard"
ENV_FILE="$REPO_ROOT/.env"
COMPOSE_ENV="$DASH_DIR/.env.compose"
ADMIN_PW_FILE="/root/inboxgenius_admin_password.txt"

[ -f "$INCOMING" ] || { echo "ERROR: $INCOMING not found" >&2; exit 1; }
for f in "$ENV_FILE" "$COMPOSE_ENV"; do
  [ ! -e "$f" ] || { echo "ERROR: $f already exists; refusing to overwrite" >&2; exit 1; }
done

PG_PASSWORD="$(openssl rand -hex 24)"
SESSION_SECRET="$(openssl rand -hex 32)"
ADMIN_PASSWORD="$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)"

# compose interpolation values
printf 'POSTGRES_PASSWORD=%s\nSITE_HOST=%s\n' "$PG_PASSWORD" "$SITE_HOST" > "$COMPOSE_ENV"

# bcrypt hash of the admin password, computed inside the API image. The password
# is passed by variable NAME (-e ADMIN_PW), never on the command line.
cd "$DASH_DIR"
docker compose -f docker-compose.prod.yml --env-file .env.compose build api >/dev/null
ADMIN_HASH="$(ADMIN_PW="$ADMIN_PASSWORD" docker compose -f docker-compose.prod.yml --env-file .env.compose \
  run --rm --no-deps -e ADMIN_PW api \
  python -c "import os, bcrypt; print(bcrypt.hashpw(os.environ['ADMIN_PW'].encode(), bcrypt.gensalt(12)).decode())")"

# Carry over the pipeline secrets, dropping keys that must not exist on the server
# or that we regenerate below.
grep -Ev '^(DATABASE_URL|NEON_DATABASE_URL|HETZNER_API_KEY|SESSION_SECRET|ADMIN_PASSWORD_HASH|ENVIRONMENT)=' \
  "$INCOMING" > "$ENV_FILE"
{
  echo ""
  echo "# --- generated by scripts/hetzner_init_secrets.sh ---"
  echo "ENVIRONMENT=production"
  echo "DATABASE_URL=postgresql://inboxgenius:${PG_PASSWORD}@postgres:5432/inboxgenius"
  echo "SESSION_SECRET=${SESSION_SECRET}"
  echo "ADMIN_PASSWORD_HASH='${ADMIN_HASH}'"
} >> "$ENV_FILE"

printf '%s\n' "$ADMIN_PASSWORD" > "$ADMIN_PW_FILE"
chmod 600 "$ENV_FILE" "$COMPOSE_ENV" "$ADMIN_PW_FILE"

echo "Secrets written (values not shown):"
echo "  $ENV_FILE  ($(grep -c '=' "$ENV_FILE") entries)"
echo "  $COMPOSE_ENV"
echo "  $ADMIN_PW_FILE  <- read this yourself: ssh root@<host> cat $ADMIN_PW_FILE"
echo "Now delete the incoming file:  shred -u $INCOMING"
